package com.example.core.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import org.json.JSONObject
import java.nio.charset.StandardCharsets
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Persisted Android device authentication session.
 * Never logged and never displayed in UI.
 */
data class StoredDeviceSession(
    val baseUrl: String,
    val bearerToken: String,
    val deviceId: String = "",
    val deviceName: String = ""
)

interface DeviceCredentialStore {
    fun saveSession(session: StoredDeviceSession)
    fun loadSession(): StoredDeviceSession?
    fun clearSession()
}

/**
 * In-memory implementation for JVM unit tests.
 */
class InMemoryDeviceCredentialStore : DeviceCredentialStore {
    @Volatile
    private var stored: StoredDeviceSession? = null

    override fun saveSession(session: StoredDeviceSession) {
        stored = session
    }

    override fun loadSession(): StoredDeviceSession? = stored

    override fun clearSession() {
        stored = null
    }
}

/**
 * Android Keystore-backed encrypted credential store (AES-256-GCM).
 *
 * Security guarantees:
 * - Symmetric AES-256 key is generated and kept exclusively inside `AndroidKeyStore`.
 * - Each write uses a fresh random GCM IV generated by the Keystore cipher.
 * - Only Base64(IV || ciphertext) is stored in private SharedPreferences; plaintext tokens
 *   are NEVER written to SharedPreferences, files, or Logcat.
 */
class AndroidKeystoreTokenStore(
    context: Context
) : DeviceCredentialStore {

    private val prefs = context.applicationContext.getSharedPreferences(
        PREFS_NAME,
        Context.MODE_PRIVATE
    )

    override fun saveSession(session: StoredDeviceSession) {
        val json = JSONObject().apply {
            put("base_url", session.baseUrl.trim())
            put("bearer_token", session.bearerToken.trim())
            put("device_id", session.deviceId.trim())
            put("device_name", session.deviceName.trim())
        }.toString()

        val secretKey = getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)
        val iv = cipher.iv
        val ciphertext = cipher.doFinal(json.toByteArray(StandardCharsets.UTF_8))

        val combined = ByteArray(1 + iv.size + ciphertext.size)
        combined[0] = iv.size.toByte()
        System.arraycopy(iv, 0, combined, 1, iv.size)
        System.arraycopy(ciphertext, 0, combined, 1 + iv.size, ciphertext.size)

        val encoded = Base64.encodeToString(combined, Base64.NO_WRAP)
        prefs.edit().putString(KEY_ENCRYPTED_SESSION, encoded).apply()
    }

    override fun loadSession(): StoredDeviceSession? {
        val encoded = prefs.getString(KEY_ENCRYPTED_SESSION, null) ?: return null
        return try {
            val combined = Base64.decode(encoded, Base64.NO_WRAP)
            if (combined.size < 14) return null
            val ivLen = combined[0].toInt() and 0xFF
            if (ivLen <= 0 || combined.size <= 1 + ivLen) return null

            val iv = combined.copyOfRange(1, 1 + ivLen)
            val ciphertext = combined.copyOfRange(1 + ivLen, combined.size)

            val secretKey = getExistingSecretKey() ?: return null
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_BITS, iv))
            val plaintext = String(cipher.doFinal(ciphertext), StandardCharsets.UTF_8)

            val obj = JSONObject(plaintext)
            val token = obj.optString("bearer_token", "").trim()
            val baseUrl = obj.optString("base_url", "").trim()
            if (token.isEmpty() || baseUrl.isEmpty()) return null

            StoredDeviceSession(
                baseUrl = baseUrl,
                bearerToken = token,
                deviceId = obj.optString("device_id", "").trim(),
                deviceName = obj.optString("device_name", "").trim()
            )
        } catch (_: Exception) {
            null
        }
    }

    override fun clearSession() {
        prefs.edit().remove(KEY_ENCRYPTED_SESSION).apply()
    }

    private fun getExistingSecretKey(): SecretKey? {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        return keyStore.getKey(KEY_ALIAS, null) as? SecretKey
    }

    private fun getOrCreateSecretKey(): SecretKey {
        getExistingSecretKey()?.let { return it }
        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .build()
        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_ALIAS = "flacdl_device_auth_aes_key_v1"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
        private const val PREFS_NAME = "flacdl_keystore_vault"
        private const val KEY_ENCRYPTED_SESSION = "enc_device_session_v1"
    }
}
